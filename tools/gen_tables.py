"""Generate src/tables.rs: the exact character classes Python's `re` uses.

The sqlparse lexer rules rely on Unicode-aware \\w, \\s, \\d and on the
case-insensitive class [A-ZÀ-Ü]. Instead of re-deriving those definitions, ask
Python itself, once, for every code point. Run: python3 tools/gen_tables.py
"""
import re
import sys

F = re.I | re.U
checks = {
    "WORD": re.compile(r"\w", re.U),
    "SPACE": re.compile(r"\s", re.U),
    "DIGIT": re.compile(r"\d", re.U),
    "ALPHA_IC": re.compile("[A-ZÀ-Ü]", F),
}

def ranges(pred):
    out, start, prev = [], None, None
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            ok = False  # not representable as a Rust char
        else:
            ok = pred(chr(cp))
        if ok:
            if start is None:
                start = cp
            prev = cp
        elif start is not None:
            out.append((start, prev)); start = None
    if start is not None:
        out.append((start, prev))
    return out

import unicodedata
lines = ["// @generated by tools/gen_tables.py (Python %s, unicodedata %s)\n" % (
    sys.version.split()[0], unicodedata.unidata_version),
    'pub const UNIDATA_VERSION: &str = "%s";\n' % unicodedata.unidata_version]
for name, rx in checks.items():
    r = ranges(lambda c, rx=rx: rx.fullmatch(c) is not None)
    lines.append("pub static %s: &[(u32, u32)] = &[%s];\n" % (name, ", ".join("(0x%X, 0x%X)" % x for x in r)))
    print(name, len(r), "ranges", file=sys.stderr)

# Non-ASCII characters that a case-insensitive ASCII letter literal also matches.
extras = {}
for letter in "abcdefghijklmnopqrstuvwxyz":
    rx = re.compile(letter, F)
    ex = [cp for cp in range(0x80, 0x110000) if not (0xD800 <= cp <= 0xDFFF) and rx.fullmatch(chr(cp))]
    if ex:
        extras[letter] = ex
print("letter extras:", {k: [hex(c) for c in v] for k, v in extras.items()}, file=sys.stderr)
arms = "\n".join("        '%s' => matches!(c as u32, %s)," % (k, " | ".join("0x%X" % c for c in v)) for k, v in extras.items())
lines.append("""
/// Does non-ASCII `c` match the ASCII letter `l` (lowercase) under re.IGNORECASE|re.UNICODE?
pub fn fold_extra(c: char, l: char) -> bool {
    match l {
%s
        _ => false,
    }
}
""" % arms)
open("src/tables.rs", "w").write("".join(lines))
